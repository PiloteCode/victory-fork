/// Lane masks read as numbers (`s_bcnt1`, `s_ff1`, `v_mbcnt`, scalar
/// compares, bit tests) are ballots of the lanes' booleans, taken where the
/// mask is written: structurisation's `active` masks hold only lanes that
/// reach that block, so the ballot misses none.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum MaskData {
    /// Compute: host lane n is console lane n (the program declares the
    /// console's wave size), so ballots are the console's masks bit for bit
    /// and any use is exact.
    Console,
    /// Pixel and vertex programs: ballots over the host's wave, whatever its
    /// size. Only uses that mean the same on any wave are allowed: counts,
    /// the first lane, the count below a lane, equality (the HLSL wave
    /// operations the console compiler expands). Lane numbers stay host
    /// lanes throughout (`v_mbcnt`, `v_readlane` at a computed lane).
    Host,
    /// Mesh programs: their lanes and waves (LDS per console wave) are the
    /// console's but no host wave size can be declared.
    None,
}

/// What a value holding a lane mask read as a number stops with.
pub(super) const LANE_MASK: Why = "a lane mask read as data";
/// A mask with lanes outside EXEC where it is written, read as a number where the lanes that
/// run that block are not all of the wave.
pub(super) const MASK_ELSEWHERE: Why = "a lane mask holding lanes elsewhere read as data";
/// A descriptor joined from the ways into a block, where one of them brings what a heap index
/// cannot stand for (an immediate sampler, say), or comes from later in the program.
pub(super) const CHOSEN: Why = "a descriptor chosen by control flow";

/// Instructions that read a lane mask (not EXEC implicitly, not a lane's
/// bit) as a number.
/// The per-lane branches (by block) whose regions hold a block of `needs` (blocks where two
/// host waves must meet, [`take_needs`]): the ones to take wave-wide
/// ([`crate::structure::structure_wide`]) so that every lane runs those blocks. None if one
/// of them is a branch whose wave-wide meaning is not known ([`Structured::wave_any`]).
pub(super) fn branches_around(st: &Structured, needs: &[usize]) -> Option<Vec<usize>> {
    let mut out = Vec::new();
    for (d, region) in lane_regions(st)? {
        if needs.iter().any(|&b| region.get(b).copied().unwrap_or(false)) {
            st.wave_any.get(d).copied().flatten()?;
            out.push(d);
        }
    }
    Some(out)
}

/// Whether a refusal is of code that needs every lane of the wave where it stands (two host
/// waves meeting there), which the other forms of the program may give it.
pub(super) fn needs_every_lane(what: &str) -> bool {
    what.ends_with("where not every lane runs") || what == MASK_ELSEWHERE
}

/// The blocks where the last lowering on this thread wanted every lane and did not have it
/// (its "... where not every lane runs" refusals), which it forgets.
pub(super) fn take_needs() -> Vec<usize> {
    NEEDS.take()
}

fn need(block: usize) {
    NEEDS.with_borrow_mut(|n| {
        if !n.contains(&block) {
            n.push(block);
        }
    });
}

/// VGPR values that are the same in every lane holding them (`all` is [`all_lane_blocks`]):
/// written by an instruction every arriving lane runs (no guard), lane by lane, from scalars,
/// constants and such values; or loaded from an address made of them. The compiler keeps
/// wave-uniform data in VGPRs and fetches it with `v_readfirstlane`.
/// With [`wave_uniform`] bit 4, an LDS read (`ds_read*`) at an address held alike in every
/// lane counts too when no LDS write of the program can run while it reads ([`lds_unraced`]):
/// every lane, in whichever host wave and at whatever time, then reads the same bytes.
/// shortcut: a value joined by a phi counts only where every predecessor is a block all lanes
/// run (no lane branch can have split the arriving lanes); loop-carried values never do.
/// With [`wave_uniform`] bit 2, a buffer load counts too where `read_only` says its view is
/// one nothing in the dispatch writes, its address is held alike (or is the offset alone) and
/// every lane runs it.
fn lane_uniform(
    p: &Program,
    st: &Structured,
    all: &[bool],
    waits: &dyn Fn(usize) -> bool,
    read_only: &dyn Fn(Site) -> bool,
) -> HashSet<Value> {
    let is_mask = |v: Value| st.masks.contains_key(&v) || st.highs.contains_key(&v);
    let own_registers = wave_uniform() & 1 != 0;
    let lds_reads = wave_uniform() & 4 != 0;
    let mut same: HashSet<Value> = HashSet::new();
    for b in crate::ir::reverse_postorder(&p.blocks) {
        let block = &p.blocks[b];
        let whole = block.preds.iter().all(|&q| all.get(q).copied().unwrap_or(false));
        for phi in &block.phis {
            if matches!(phi.reg, Reg::V(_)) && whole && phi.args.iter().all(|a| same.contains(a)) {
                same.insert(phi.value);
            }
        }
        for (i, inst) in block.insts.iter().enumerate() {
            let name = inst.name();
            if let Fields::Ds {
                addr: Some(Operand::Vector { reg, .. }),
                gds: false,
                ..
            } = inst.fields
                && lds_reads
                && name.starts_with("ds_read")
                && st.guards[b][i].is_none()
                && inst.read(Reg::V(reg)).is_some_and(|a| same.contains(&a))
                && lds_unraced(p, (b, i), waits)
            {
                same.extend(inst.writes.iter().filter(|w| matches!(w.0, Reg::V(_))).map(|w| w.1));
                continue;
            }
            if let Fields::Buffer {
                addr: Operand::Vector { reg, dwords },
                offen,
                idxen,
                lds: false,
                tfe: false,
                ..
            } = inst.fields
                && name.contains("_load_")
                && st.guards[b][i].is_none()
                && read_only((b, i))
            {
                // without `offen` and `idxen` the address register is not read
                let addressed = !(offen || idxen)
                    || (reg..reg.saturating_add(dwords)).all(|r| inst.read(Reg::V(r)).is_some_and(|a| same.contains(&a)));
                if addressed {
                    same.extend(inst.writes.iter().filter(|w| matches!(w.0, Reg::V(_))).map(|w| w.1));
                }
                continue;
            }
            let ops: Vec<Operand> = match &inst.fields {
                Fields::Valu(v)
                    if v.dpp.is_none()
                        && v.sdwa.is_none()
                        && !name.starts_with("v_mbcnt")
                        && !name.starts_with("v_cmpx")
                        && !name.contains("lane") =>
                {
                    v.src.clone()
                }
                _ => continue,
            };
            if st.guards[b][i].is_some() {
                continue; // lanes outside EXEC keep another value
            }
            // `VICTORY_WAVE_UNIFORM` bit 1: an operand is its own registers; of the other VGPRs
            // the instruction reads, the old values of those it writes (kept in the lanes a
            // guard masks; unguarded here) do not count. Not for what accumulates into its
            // destination or reads registers by M0.
            let own = own_registers && !(name.contains("mac") || name.contains("dot") || name.contains("movrel"));
            let alike = ops.iter().all(|op| match *op {
                Operand::Vector { reg, dwords } => {
                    // every dword of the operand the instruction reads from that register on
                    let end = if own { reg.saturating_add(dwords.max(1)) } else { u8::MAX };
                    let read: Vec<Value> = inst
                        .reads
                        .iter()
                        .filter(|r| matches!(r.0, Reg::V(x) if x >= reg && (x < end || !own)))
                        .map(|r| r.1)
                        .collect();
                    !read.is_empty() && read.iter().all(|x| same.contains(x))
                }
                // a scalar is one value; a lane mask is not, unless a compare of such values made it
                Operand::Scalar { code, .. } if code != NULL => {
                    inst.read(Reg::S(code)).is_none_or(|x| !is_mask(x) || same.contains(&x))
                }
                _ => true,
            }) && (!own || {
                let in_operand = |x: u8| {
                    ops.iter().any(|op| matches!(*op, Operand::Vector { reg, dwords } if x >= reg && x < reg.saturating_add(dwords.max(1))))
                };
                let written = |x: u8| inst.writes.iter().any(|w| w.0 == Reg::V(x));
                inst.reads.iter().all(|r| match r.0 {
                    Reg::V(x) if !in_operand(x) => written(x) || same.contains(&r.1),
                    _ => true,
                })
            });
            if alike {
                same.extend(inst.writes.iter().filter(|w| w.0 != Reg::Scc).map(|w| w.1));
            }
        }
    }
    same
}

/// Whether no LDS write can run while the read at `at` does, in any wave of the group: none
/// lies in the stretch between group barriers that holds the read. The stretch starts where
/// the read can be reached from without passing a barrier (going back to the barriers, or the
/// entry, it comes from); everything those starts reach without passing a barrier is
/// searched, so a write on another branch of the same stretch counts too. A barrier counts
/// only where the host waits there for the whole group (`waits`, by block). A write is a
/// `ds_` instruction other than a read, swizzle or permute, or a buffer or flat load into LDS;
/// an indirect jump ends the search with a no.
fn lds_unraced(p: &Program, at: (usize, usize), waits: &dyn Fn(usize) -> bool) -> bool {
    let writes = |inst: &Inst| match &inst.fields {
        Fields::Ds { .. } => {
            let n = inst.name();
            !(n.starts_with("ds_read") || matches!(n, "ds_swizzle_b32" | "ds_permute_b32" | "ds_bpermute_b32" | "ds_nop"))
        }
        Fields::Buffer { lds, .. } | Fields::Flat { lds, .. } => *lds,
        _ => false,
    };
    let barrier = |b: usize, inst: &Inst| inst.name() == "s_barrier" && waits(b);
    // Back from the read: the points the stretch starts at.
    let mut starts: Vec<(usize, usize)> = Vec::new();
    let mut seen = vec![false; p.blocks.len()];
    let mut back = vec![at];
    while let Some((b, end)) = back.pop() {
        let insts = &p.blocks[b].insts;
        let mut started = false;
        for j in (0..end.min(insts.len())).rev() {
            if barrier(b, &insts[j]) {
                starts.push((b, j + 1));
                started = true;
                break;
            }
            if writes(&insts[j]) {
                return false;
            }
        }
        if started {
            continue;
        }
        if b == 0 || p.blocks[b].preds.is_empty() {
            starts.push((b, 0));
        }
        for &q in &p.blocks[b].preds {
            if !std::mem::replace(&mut seen[q], true) {
                back.push((q, p.blocks[q].insts.len()));
            }
        }
    }
    // Forward from the starts to the barriers that end the stretch.
    let mut seen = vec![false; p.blocks.len()];
    let mut ahead = starts;
    while let Some((b, from)) = ahead.pop() {
        let block = &p.blocks[b];
        let mut ended = false;
        for inst in block.insts.iter().skip(from) {
            if barrier(b, inst) {
                ended = true;
                break;
            }
            if writes(inst) {
                return false;
            }
        }
        if ended {
            continue;
        }
        if matches!(block.exit, crate::ir::Exit::Indirect) {
            return false;
        }
        for s in block.exit.successors() {
            if !std::mem::replace(&mut seen[s], true) {
                ahead.push((s, 0));
            }
        }
    }
    true
}

/// The paired form: scalar values each console lane has its own of in the lowering, a waterfall
/// loop's first-lane reads (the lane's own dword, `resource::Waterfall`) and what scalar code
/// and joins make of them.
fn lane_scalars(p: &Program, res: &Resources) -> HashSet<Value> {
    let mut own: HashSet<Value> = res.waterfall.reads.iter().copied().collect();
    if own.is_empty() {
        return own;
    }
    let order = crate::ir::reverse_postorder(&p.blocks);
    loop {
        let before = own.len();
        for &b in &order {
            let block = &p.blocks[b];
            for phi in &block.phis {
                if !matches!(phi.reg, Reg::V(_)) && phi.args.iter().any(|a| own.contains(a)) {
                    own.insert(phi.value);
                }
            }
            for inst in &block.insts {
                if matches!(inst.fields, Fields::Sop { .. } | Fields::Smem { .. })
                    && inst.reads.iter().any(|r| own.contains(&r.1))
                {
                    own.extend(inst.writes.iter().map(|w| w.1));
                }
            }
        }
        if own.len() == before {
            return own;
        }
    }
}

/// The mode of a group barrier the translation adds (host waves meeting):
/// a wait for the group with a shared-memory fence; the fence alone with
/// `VICTORY_GROUP_SYNC=0` ([`super::group_sync`]).
fn meeting_mode() -> u32 {
    if super::group_sync() == 0 { 8 } else { 1 | 8 }
}

/// LDS accesses of a console wave run as two host waves, where some sit in blocks that only
/// some lanes run (`all` is [`all_lane_blocks`]): per IR block, whether the host waves meet (a
/// group barrier) at its start and before its exit. `None` if barriers cannot keep the
/// console's order.
///
/// The console runs the wave's lanes in step, so an LDS write is seen by every later read. Two
/// host waves keep that order if they meet between any two accesses of which one writes. A
/// barrier must be run by every thread, so it cannot stand in a lane branch's region; but
/// every way into and out of such a region passes a block all lanes run, and the waves meet
/// there: before the exit of an all-lane block into a region with LDS accesses, and at the
/// start of an all-lane block entered from one. Accesses in all-lane blocks get their own
/// barrier as before. What that cannot order is a write and a read inside one region (blocks
/// joined without an all-lane block between them): refused.
/// shortcut: two writes in one region are taken not to hit the same dword from both halves.
fn lds_meetings(p: &crate::ir::Program, st: &Structured, all: &[bool]) -> Option<Vec<(bool, bool)>> {
    let n = st.exits.len();
    let succ = |b: usize| -> Vec<usize> {
        match st.exits[b] {
            LaneExit::Jump(t) => vec![t],
            LaneExit::Branch { taken, not_taken, .. } => vec![taken, not_taken],
            LaneExit::End | LaneExit::Indirect => Vec::new(),
        }
    };
    // regions: blocks not every lane runs, joined by the edges between them
    let mut region: Vec<usize> = (0..n).collect();
    fn find(region: &mut [usize], mut b: usize) -> usize {
        while region[b] != b {
            region[b] = region[region[b]];
            b = region[b];
        }
        b
    }
    for b in 0..n {
        for t in succ(b) {
            if !all[b] && !all[t] {
                let (x, y) = (find(&mut region, b), find(&mut region, t));
                region[x] = y;
            }
        }
    }
    // per region: LDS reads, LDS writes
    let mut reads = vec![false; n];
    let mut writes = vec![false; n];
    for (b, block) in p.blocks.iter().enumerate().take(n) {
        if all[b] {
            continue;
        }
        let r = find(&mut region, b);
        for i in &block.insts {
            let name = i.name();
            if !matches!(i.fields, Fields::Ds { .. }) || name.starts_with("ds_swizzle") || name.contains("permute") {
                continue;
            }
            if name.starts_with("ds_read") {
                reads[r] = true;
            } else {
                writes[r] = true;
            }
        }
    }
    if (0..n).any(|r| reads[r] && writes[r]) {
        if std::env::var_os("VICTORY_WAVE_WHY").is_some() {
            for r in (0..n).filter(|&r| reads[r] && writes[r]) {
                let mut list = Vec::new();
                for (b, block) in p.blocks.iter().enumerate().take(n) {
                    if all[b] || find(&mut region, b) != r {
                        continue;
                    }
                    for i in block.insts.iter().filter(|i| matches!(i.fields, Fields::Ds { .. })) {
                        list.push(format!("{:#x} {}", i.machine.offset, i.name()));
                    }
                }
                eprintln!("WAVE64-LDS-REGION [{}]", list.join(", "));
            }
        }
        return None;
    }
    let mut meet = vec![(false, false); n];
    for b in 0..n {
        for t in succ(b) {
            if all[b] && !all[t] {
                let r = find(&mut region, t);
                meet[b].1 |= reads[r] || writes[r];
            } else if !all[b] && all[t] {
                let r = find(&mut region, b);
                meet[t].0 |= reads[r] || writes[r];
            }
        }
    }
    Some(meet)
}

/// Masks held as numbers or constant lane sets in guards or lane branches: the lane tests its
/// own bit by its console lane.
fn lane_constant_masks(st: &Structured) -> bool {
    let whens = st.exits.iter().filter_map(|e| match *e {
        LaneExit::Branch { when, .. } => Some(when),
        _ => None,
    });
    let mut work: Vec<Bool> = st.guards.iter().flatten().flatten().copied().chain(whens).collect();
    // Through lane-mask joins too: an edge that brings a number or a constant lane set needs
    // the lane's own bit of it.
    // shortcut: masks only selects read (`v_cndmask_b32`, carries in) are not followed; such
    // a program still stops with "a constant lane mask" or "an opaque lane mask".
    let (mut seen, mut joins) = (HashSet::new(), HashSet::new());
    while let Some(g) = work.pop() {
        if !seen.insert(g) {
            continue;
        }
        for a in st.bools.support(g) {
            match a {
                Atom::Opaque(_) | Atom::Constant(_) => return true,
                Atom::Phi(id) if joins.insert(id) => {
                    if let Some(edges) = st.phi_masks.get(&id) {
                        work.extend(edges.iter().copied());
                    }
                }
                _ => {}
            }
        }
    }
    false
}

